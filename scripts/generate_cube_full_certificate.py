#!/usr/bin/env python3
"""Generate a kernel-checkable certificate excluding consecutive 3-full numbers.

The generator is not part of the trusted proof.  Lean checks each supplied prime,
its divisibility witness, and the entire coverage of 1 <= n <= 100000.
"""

from pathlib import Path

BOUND = 100_000
CHUNK = 4096
SMALL_PRIMES = (2, 3, 5, 7)
ROOT = Path(__file__).resolve().parents[1]


def bad_prime(n: int, p: int) -> bool:
    return n % p == 0 and n % (p**3) != 0


def main() -> None:
    spf = list(range(BOUND + 2))
    for p in range(2, int((BOUND + 1) ** 0.5) + 1):
        if spf[p] == p:
            for n in range(p * p, BOUND + 2, p):
                if spf[n] == n:
                    spf[n] = p

    bad_factors: list[list[int]] = [[] for _ in range(BOUND + 2)]
    for n in range(1, BOUND + 2):
        m = n
        while m > 1:
            p = spf[m]
            exponent = 0
            while m % p == 0:
                m //= p
                exponent += 1
            if exponent < 3:
                bad_factors[n].append(p)

    full = [n for n in range(1, BOUND + 2) if not bad_factors[n]]
    assert not any(not bad_factors[n] and not bad_factors[n + 1]
                   for n in range(1, BOUND + 1))

    header = '''import Mathlib

/-!
# No consecutive 3-full integers below 100001

This file refutes only the finite proposed step
`Erdos366.erdos_366.variants.weaker.R1.H1`.  It makes no assertion
about the unbounded existence question.

For each n, a prime divisor of n or n + 1 whose cube does not divide that
integer is enough.  The checker tries the four small primes first.  Only
the remaining cases consume an entry from the supplied certificate.
All computation is checked by the Lean kernel; there is no native_decide.

Generated by scripts/generate_cube_full_certificate.py.
-/

namespace CubeFull

set_option maxRecDepth 1000000
set_option maxHeartbeats 0

/-- The prime-divisor formulation of being 3-full. -/
def IsCubeFull (n : Nat) : Prop :=
  ∀ p : Nat, p.Prime → p ∣ n → p ^ 3 ∣ n

/-- This is exactly the prime-factor predicate used by `Nat.Full 3` in the
Formal Conjectures library, including the case n = 0. -/
theorem isCubeFull_iff_primeFactors (n : Nat) :
    IsCubeFull n ↔ ∀ p ∈ n.primeFactors, p ^ 3 ∣ n := by
  constructor
  · intro h p hp
    obtain ⟨hprime, hdiv, _⟩ := Nat.mem_primeFactors.mp hp
    exact h p hprime hdiv
  · intro h p hprime hdiv
    by_cases hn : n = 0
    · simp [hn]
    · exact h p (Nat.mem_primeFactors.mpr ⟨hprime, hdiv, hn⟩)

/-- A prime witnessing that one of the two consecutive integers is not 3-full. -/
def BadPrime (n p : Nat) : Prop :=
  p.Prime ∧ ((p ∣ n ∧ ¬ p ^ 3 ∣ n) ∨
    (p ∣ n + 1 ∧ ¬ p ^ 3 ∣ n + 1))

instance (n p : Nat) : Decidable (BadPrime n p) :=
  inferInstanceAs (Decidable (p.Prime ∧ ((p ∣ n ∧ ¬ p ^ 3 ∣ n) ∨
    (p ∣ n + 1 ∧ ¬ p ^ 3 ∣ n + 1))))

def SmallWitness (n : Nat) : Prop :=
  BadPrime n 2 ∨ BadPrime n 3 ∨ BadPrime n 5 ∨ BadPrime n 7

instance (n : Nat) : Decidable (SmallWitness n) :=
  inferInstanceAs (Decidable
    (BadPrime n 2 ∨ BadPrime n 3 ∨ BadPrime n 5 ∨ BadPrime n 7))

/-- Check an interval in increasing order, consuming one supplied prime only
when none of the four small primes is already a witness. -/
def check : Nat → Nat → List Nat → Bool
  | _, 0, _ => true
  | start, count + 1, witnesses =>
      if SmallWitness start then
        check (start + 1) count witnesses
      else
        match witnesses with
        | [] => false
        | p :: rest => decide (BadPrime start p) && check (start + 1) count rest

theorem check_sound : ∀ (count start : Nat) (witnesses : List Nat),
    check start count witnesses = true →
    ∀ n : Nat, start ≤ n → n < start + count → ∃ p : Nat, BadPrime n p := by
  intro count
  induction count with
  | zero =>
      intro start witnesses hcheck n hlow hhigh
      omega
  | succ count ih =>
      intro start witnesses hcheck n hlow hhigh
      by_cases hsmall : SmallWitness start
      · rw [check, if_pos hsmall] at hcheck
        by_cases hn : n = start
        · subst n
          rcases hsmall with h | h | h | h
          · exact ⟨2, h⟩
          · exact ⟨3, h⟩
          · exact ⟨5, h⟩
          · exact ⟨7, h⟩
        · exact ih (start + 1) witnesses hcheck n (by omega) (by omega)
      · rw [check, if_neg hsmall] at hcheck
        cases witnesses with
        | nil => simp at hcheck
        | cons p rest =>
            have hboth : decide (BadPrime start p) = true ∧
                check (start + 1) count rest = true := Bool.and_eq_true_iff.mp hcheck
            by_cases hn : n = start
            · subst n
              exact ⟨p, of_decide_eq_true hboth.1⟩
            · exact ih (start + 1) rest hboth.2 n (by omega) (by omega)

'''
    chunks: list[tuple[int, int, list[int]]] = []
    for start in range(1, BOUND + 1, CHUNK):
        count = min(CHUNK, BOUND + 1 - start)
        witnesses = []
        for n in range(start, start + count):
            if any(bad_prime(n, p) or bad_prime(n + 1, p) for p in SMALL_PRIMES):
                continue
            p = min(bad_factors[n] + bad_factors[n + 1])
            assert spf[p] == p
            assert bad_prime(n, p) or bad_prime(n + 1, p)
            witnesses.append(p)
        chunks.append((start, count, witnesses))

    parts = [header]
    for i, (start, count, witnesses) in enumerate(chunks):
        rows = [", ".join(map(str, witnesses[j:j + 16]))
                for j in range(0, len(witnesses), 16)]
        literal = ",\n    ".join(rows)
        parts.append(f"private def witnesses{i} : List Nat :=\n  [{literal}]\n\n")
        parts.append(f"private theorem block{i} : check {start} {count} witnesses{i} = true := by\n"
                     "  decide +kernel\n\n")

    parts.append('''/-- A certified prime obstruction for every n in the requested interval. -/
theorem bounded_badPrime (n : Nat) (hn : 1 ≤ n) (hbound : n ≤ 100000) :
    ∃ p : Nat, BadPrime n p := by
''')
    for i, (start, count, _) in enumerate(chunks):
        if i < len(chunks) - 1:
            parts.append(f"  by_cases h{i} : n < {start + count}\n")
            parts.append(f"  · exact check_sound {count} {start} witnesses{i} block{i} n (by omega) h{i}\n")
        else:
            parts.append(f"  exact check_sound {count} {start} witnesses{i} block{i} n (by omega) (by omega)\n\n")

    parts.append('''/-- No positive n at most 100000 has both n and n + 1 3-full. -/
theorem no_consecutive (n : Nat) (hn : 1 ≤ n) (hbound : n ≤ 100000) :
    ¬ (IsCubeFull n ∧ IsCubeFull (n + 1)) := by
  rintro ⟨hleft, hright⟩
  obtain ⟨p, hp, hbad⟩ := bounded_badPrime n hn hbound
  rcases hbad with ⟨hdiv, hnot⟩ | ⟨hdiv, hnot⟩
  · exact hnot (hleft p hp hdiv)
  · exact hnot (hright p hp hdiv)

theorem refutesBoundedExistence :
    ¬ ∃ n : Nat, 0 < n ∧ n ≤ 100000 ∧ IsCubeFull n ∧ IsCubeFull (n + 1) := by
  rintro ⟨n, hn, hbound, hleft, hright⟩
  exact no_consecutive n hn hbound ⟨hleft, hright⟩

end CubeFull
''')

    target = ROOT / "Additional" / "CubeFull.lean"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("".join(parts))
    print(f"Wrote {target}")
    print(f"Checked candidate interval: 1 <= n <= {BOUND}")
    print(f"3-full integers in 1..{BOUND + 1}: {len(full)}")
    print("Consecutive 3-full pairs: 0")
    print(f"Supplied prime witnesses after the small-prime sieve: {sum(len(ws) for _, _, ws in chunks)}")
    print(f"Kernel certificate chunks: {len(chunks)}")


if __name__ == "__main__":
    main()
